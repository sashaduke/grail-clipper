// Emits tests/clipper/tree_cases.grl: ClipperD solutions as PolyTreeD (precision 2 and 8) and as
// paths, compared by depth-first node order, level, hole flag and exact binary64 point bits.
//   clang++ -std=c++17 -O1 -I<clipper2>/include tree_cases.cpp <clipper2>/src/clipper.engine.cpp -o trees
#include "clipper2/clipper.h"
#include <cstdio>
#include <cstdint>
#include <cstring>
using namespace Clipper2Lib;
static uint64_t st = 0x9E3779B97F4A7C15ull;
static double rnd01() { st ^= st << 13; st ^= st >> 7; st ^= st << 17; return (double)(st >> 11) / 9007199254740992.0; }
static uint64_t bits(double d) { uint64_t u; std::memcpy(&u, &d, 8); return u; }
static void lit(double v) { char b[64]; std::snprintf(b, sizeof b, "%.17g", v); bool plain = true; for (char *c = b; *c; ++c) if (*c == '.' || *c == 'e' || *c == 'n' || *c == 'i') plain = false; std::printf("%s%s", b, plain ? ".0" : ""); }
static PathD ring(double cx, double cy, double r, int n, double jitter, bool rev) {
  PathD p; for (int i = 0; i < n; ++i) { double a = 6.283185307179586 * i / n, rr = r * (1 + jitter * (rnd01() - 0.5)); p.push_back(PointD(cx + rr * std::cos(a), cy + rr * std::sin(a))); }
  if (rev) std::reverse(p.begin(), p.end()); return p; }
static void emit_paths(const char *var, const PathsD &ps) {
  std::printf("        mut %s = clipper::paths_d();\n", var);
  for (auto &p : ps) {
    std::printf("        clipper::push_path_d(&mut %s, f64[", var);
    for (size_t i = 0; i < p.size(); ++i) { std::printf("%s", i ? ", " : ""); lit(p[i].x); }
    std::printf("], f64[");
    for (size_t i = 0; i < p.size(); ++i) { std::printf("%s", i ? ", " : ""); lit(p[i].y); }
    std::printf("]);\n");
  }
}
static void dfs(const PolyPathD &n, std::vector<const PolyPathD *> &out) { for (auto &c : n) { out.push_back(c.get()); dfs(*c, out); } }
static const char *ct_name[] = {"CLIP_NONE", "CLIP_INTERSECTION", "CLIP_UNION", "CLIP_DIFFERENCE", "CLIP_XOR"};
static const char *fr_name[] = {"FILL_EVEN_ODD", "FILL_NON_ZERO", "FILL_POSITIVE", "FILL_NEGATIVE"};
static int n_case = 0;
static void emit(const PathsD &s, const PathsD &k, ClipType ct, FillRule fr, int prec) {
  PolyTreeD tree; BooleanOp(ct, fr, s, k, tree, prec);
  std::vector<const PolyPathD *> nodes; dfs(tree, nodes);
  std::printf("    {\n        // tree case %d\n", n_case);
  emit_paths("s", s); emit_paths("k", k);
  std::printf("        t := clipper::boolean_op_tree_d(clipper::%s, clipper::%s, s, k, %d);\n", ct_name[(int)ct], fr_name[(int)fr], prec);
  std::printf("        want := u64[");
  bool first = true;
  auto put = [&](uint64_t v) { std::printf("%s%llu", first ? "" : ", ", (unsigned long long)v); first = false; };
  put(nodes.size());
  for (auto *n : nodes) { put(n->Level()); put(n->IsHole()); put(n->Polygon().size()); for (auto &p : n->Polygon()) { put(bits(p.x)); put(bits(p.y)); } }
  std::printf("];\n        bad += compare_tree(%d, &t, &want);\n    }\n", n_case++);
}
int main() {
  std::printf("// Generated by tests/reference/clipper/tree_cases.cpp from Clipper2; do not edit.\nuse clipper;\n\n");
  std::printf("fn dfs<a>(t: (&a clipper::Tree), node: u64, out: (&a mut u64[])) {\n    for i in clipper::tree_count(&t) {\n        if t.parent[i] == node {\n            out.push(i);\n            dfs(&t, i, &mut out);\n        }\n    }\n}\n");
  std::printf("fn compare_tree<a, b>(n: u64, t: (&a clipper::Tree), want: (&b u64[])) -> u64 {\n    mut order = u64[];\n    dfs(&t, 0, &mut order);\n    mut got = u64[order.len()];\n");
  std::printf("    for k in order.len() {\n        i := order[k];\n        got.push(clipper::tree_level(&t, i));\n        mut h: u64 = 0;\n        if clipper::tree_is_hole(&t, i) {\n            h = 1;\n        }\n        got.push(h);\n        got.push(t.x[i].len());\n        for j in t.x[i].len() {\n            got.push(bits(t.x[i][j]));\n            got.push(bits(t.y[i][j]));\n        }\n    }\n");
  std::printf("    if got.len() != want.len() {\n        println(\"tree case {}: {} words, expected {}\", n, got.len(), want.len());\n        return 1;\n    }\n    for i in got.len() {\n        if got[i] != want[i] {\n            println(\"tree case {}: word {} differs\", n, i);\n            return 1;\n        }\n    }\n    return 0;\n}\n\nfn main() -> u64 {\n    mut bad: u64 = 0;\n");
  // Nested islands and lakes (outer, hole, island in hole) and overlapping blobs.
  for (int k = 0; k < 24; ++k) {
    PathsD s{ring(0, 0, 100, 40, 0.2, false), ring(5, 3, 55, 30, 0.2, true), ring(8, 6, 20, 16, 0.3, false)};
    PathsD c{ring(60 * rnd01() - 30, 60 * rnd01() - 30, 40 + 30 * rnd01(), 24, 0.4, false)};
    if (k % 2) c.push_back(ring(-70, 40, 25, 12, 0.3, false));
    emit(s, c, (ClipType)(1 + k % 4), (FillRule)((k / 4) % 4), k % 3 == 0 ? 8 : 2);
  }
  // Random self-intersecting polygons at fractional coordinates.
  for (int k = 0; k < 16; ++k) {
    PathD a, b; for (int i = 0; i < 9; ++i) a.push_back(PointD(200 * rnd01() - 100, 200 * rnd01() - 100));
    for (int i = 0; i < 7; ++i) b.push_back(PointD(200 * rnd01() - 100, 200 * rnd01() - 100));
    emit(PathsD{a}, PathsD{b}, (ClipType)(1 + k % 4), (FillRule)(k % 4), k % 2 ? 8 : 3);
  }
  std::printf("    println(\"clipper trees: {} of %d cases differ\", bad);\n    return bad;\n}\n", n_case);
  return 0;
}
