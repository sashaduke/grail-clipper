// Emits tests/clipper/offset_cases.grl: InflatePaths(PathsD) results for every join and end type,
// compared as exact binary64 point bits.
//   clang++ -std=c++17 -O1 -I<clipper2>/include offset_cases.cpp <clipper2>/src/clipper.engine.cpp <clipper2>/src/clipper.offset.cpp -o offsets
#include "clipper2/clipper.h"
#include <cstdio>
#include <cstdint>
#include <cstring>
using namespace Clipper2Lib;
static uint64_t st = 0xD1B54A32D192ED03ull;
static double rnd01() { st ^= st << 13; st ^= st >> 7; st ^= st << 17; return (double)(st >> 11) / 9007199254740992.0; }
static uint64_t bits(double d) { uint64_t u; std::memcpy(&u, &d, 8); return u; }
static void lit(double v) { char b[64]; std::snprintf(b, sizeof b, "%.17g", v); bool plain = true; for (char *c = b; *c; ++c) if (*c == '.' || *c == 'e' || *c == 'n' || *c == 'i') plain = false; std::printf("%s%s", b, plain ? ".0" : ""); }
static const char *join_names[] = {"JOIN_SQUARE", "JOIN_BEVEL", "JOIN_ROUND", "JOIN_MITER"};
static const char *end_names[] = {"END_POLYGON", "END_JOINED", "END_BUTT", "END_SQUARE", "END_ROUND"};
static int n_case = 0;
static void emit(const PathsD &in, double delta, JoinType jt, EndType et, double miter, int prec, double arc) {
  PathsD out = InflatePaths(in, delta, jt, et, miter, prec, arc);
  std::printf("    {\n        // offset case %d\n        mut s = clipper::paths_d();\n", n_case);
  for (auto &p : in) {
    std::printf("        clipper::push_path_d(&mut s, f64[");
    for (size_t i = 0; i < p.size(); ++i) { std::printf("%s", i ? ", " : ""); lit(p[i].x); }
    std::printf("], f64[");
    for (size_t i = 0; i < p.size(); ++i) { std::printf("%s", i ? ", " : ""); lit(p[i].y); }
    std::printf("]);\n");
  }
  std::printf("        got := clipper::inflate_paths_d(s, "); lit(delta);
  std::printf(", clipper::%s, clipper::%s, clipper::OffsetOptions { miter_limit: ", join_names[(int)jt], end_names[(int)et]); lit(miter);
  std::printf(", precision: %d, arc_tolerance: ", prec); lit(arc); std::printf(" });\n        want := u64[%zu", out.size());
  for (auto &p : out) { std::printf(", %zu", p.size()); for (auto &q : p) std::printf(", %llu, %llu", (unsigned long long)bits(q.x), (unsigned long long)bits(q.y)); }
  std::printf("];\n        bad += compare_d(%d, &got, &want);\n    }\n", n_case++);
}
static PathD ring(double cx, double cy, double r, int n, double jit) { PathD p; for (int i = 0; i < n; ++i) { double a = 6.283185307179586 * i / n, rr = r * (1 + jit * (rnd01() - 0.5)); p.push_back(PointD(cx + rr * std::cos(a), cy + rr * std::sin(a))); } return p; }
int main() {
  std::printf("// Generated by tests/reference/clipper/offset_cases.cpp from Clipper2; do not edit.\nuse clipper;\n\n");
  std::printf("fn compare_d<a, b>(n: u64, got: (&a clipper::PathD[]), want: (&b u64[])) -> u64 {\n    mut w = u64[got.len()];\n    for i in got.len() {\n        w.push(got[i].x.len());\n        for j in got[i].x.len() {\n            w.push(bits(got[i].x[j]));\n            w.push(bits(got[i].y[j]));\n        }\n    }\n");
  std::printf("    if w.len() != want.len() {\n        println(\"offset case {}: {} words, expected {}\", n, w.len(), want.len());\n        return 1;\n    }\n    for i in w.len() {\n        if w[i] != want[i] {\n            println(\"offset case {}: word {} differs\", n, i);\n            return 1;\n        }\n    }\n    return 0;\n}\n\nfn main() -> u64 {\n    mut bad: u64 = 0;\n");
  PathsD square{{PointD(0.0, 0.0), PointD(10.0, 0.0), PointD(10.0, 10.0), PointD(0.0, 10.0)}};
  PathsD concave{{PointD(0.0, 0.0), PointD(10.0, 0.0), PointD(10.0, 10.0), PointD(5.0, 4.0), PointD(0.0, 10.0)}};
  PathsD polyline{{PointD(0.0, 0.0), PointD(5.5, 2.25), PointD(9.0, -3.5), PointD(14.75, 4.0)}};
  PathsD river{{PointD(0.0, 0.0), PointD(20.125, 3.5), PointD(41.5, -2.75), PointD(60.25, 8.5), PointD(80.0, 0.5)}};
  PathsD point{{PointD(3.25, 4.5)}};
  for (int jt = 0; jt < 4; ++jt) {
    emit(square, 1.5, (JoinType)jt, EndType::Polygon, 2.0, 2, 0.0);
    emit(square, -1.25, (JoinType)jt, EndType::Polygon, 2.0, 2, 0.0);
    emit(concave, 2.0, (JoinType)jt, EndType::Polygon, 3.0, 3, 0.0);
    for (int et = 1; et < 5; ++et) emit(polyline, 1.0, (JoinType)jt, (EndType)et, 2.0, 2, 0.0);
  }
  // Abundance water_geometry: Round/Round, miter 2, precision 3, explicit arc tolerance.
  for (double arc : {0.0, 0.01, 0.05, 0.25}) for (double w : {0.75, 2.5, 6.0}) emit(river, w, JoinType::Round, EndType::Round, 2.0, 3, arc);
  emit(point, 2.0, JoinType::Round, EndType::Polygon, 2.0, 2, 0.0);
  emit(point, 2.0, JoinType::Square, EndType::Polygon, 2.0, 2, 0.0);
  for (int k = 0; k < 12; ++k) emit(PathsD{ring(0, 0, 30, 24, 0.5)}, (k % 2 ? -1 : 1) * (0.5 + 4 * rnd01()), (JoinType)(k % 4), EndType::Polygon, 2.0, k % 3 + 1, 0.0);
  std::printf("    println(\"clipper offsets: {} of %d cases differ\", bad);\n    return bad;\n}\n", n_case);
  return 0;
}
