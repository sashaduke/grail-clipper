// Emits tests/clipper/cases.grl: Clipper2 (Clipper64) solutions for generated boolean cases,
// exact paths in output order, and a Grail program that recomputes them with lib/clipper.grl.
//   clang++ -std=c++17 -O1 -I<clipper2>/include clipper_cases.cpp <clipper2>/src/clipper.engine.cpp -o cases
#include "clipper2/clipper.h"
#include <cstdio>
#include <cstdint>
#include <vector>
using namespace Clipper2Lib;

static uint64_t st = 0x2545F4914F6CDD1Dull;
static int64_t rnd(int64_t n) { st ^= st << 13; st ^= st >> 7; st ^= st << 17; return (int64_t)(st % (uint64_t)n); }
static Path64 random_poly(int n, int64_t span) { Path64 p; for (int i = 0; i < n; ++i) p.push_back(Point64(rnd(span), rnd(span))); return p; }
static Path64 rect(int64_t l, int64_t t, int64_t r, int64_t b) { return Path64{Point64(l, t), Point64(r, t), Point64(r, b), Point64(l, b)}; }
static void emit_paths(const char *var, const Paths64 &ps) {
  std::printf("    mut %s = clipper::paths();\n", var);
  for (auto &p : ps) {
    std::printf("    clipper::push_path(&mut %s, i64[", var);
    for (size_t i = 0; i < p.size(); ++i) std::printf("%s%lld", i ? ", " : "", (long long)p[i].x);
    std::printf("], i64[");
    for (size_t i = 0; i < p.size(); ++i) std::printf("%s%lld", i ? ", " : "", (long long)p[i].y);
    std::printf("]);\n");
  }
}
static const char *ct_name[] = {"CLIP_NONE", "CLIP_INTERSECTION", "CLIP_UNION", "CLIP_DIFFERENCE", "CLIP_XOR"};
static const char *fr_name[] = {"FILL_EVEN_ODD", "FILL_NON_ZERO", "FILL_POSITIVE", "FILL_NEGATIVE"};
static int case_no = 0;
static void emit(const Paths64 &subj, const Paths64 &clip, ClipType ct, FillRule fr) {
  Clipper64 c; c.AddSubject(subj); if (!clip.empty()) c.AddClip(clip);
  Paths64 sol; c.Execute(ct, fr, sol);
  std::printf("    {\n        // case %d\n        mut c = clipper::new();\n", case_no++);
  emit_paths("s", subj); std::printf("        clipper::add_subject(&mut c, s);\n");
  if (!clip.empty()) { emit_paths("k", clip); std::printf("        clipper::add_clip(&mut c, k);\n"); }
  emit_paths("want", sol);
  std::printf("        got := clipper::execute(&mut c, clipper::%s, clipper::%s);\n", ct_name[(int)ct], fr_name[(int)fr]);
  std::printf("        bad += compare(%d, &got, &want);\n    }\n", case_no - 1);
}
int main() {
  std::printf("// Generated by tests/reference/clipper/clipper_cases.cpp from Clipper2; do not edit.\nuse clipper;\n\n");
  std::printf("fn compare<a, b>(n: u64, got: (&a clipper::Path[]), want: (&b clipper::Path[])) -> u64 {\n");
  std::printf("    if got.len() != want.len() {\n        println(\"case {}: {} paths, expected {}\", n, got.len(), want.len());\n        return 1;\n    }\n");
  std::printf("    for i in got.len() {\n        if got[i].x.len() != want[i].x.len() {\n            println(\"case {}: path {} has {} points, expected {}\", n, i, got[i].x.len(), want[i].x.len());\n            return 1;\n        }\n");
  std::printf("        for j in got[i].x.len() {\n            if (got[i].x[j] != want[i].x[j]) || (got[i].y[j] != want[i].y[j]) {\n                println(\"case {}: path {} point {} differs\", n, i, j);\n                return 1;\n            }\n        }\n    }\n    return 0;\n}\n\n");
  std::printf("fn main() -> u64 {\n    mut bad: u64 = 0;\n");
  // Hand-made shapes: overlapping squares, nested holes, shared edges, horizontals, collinear.
  Paths64 sq1{rect(0, 0, 100, 100)}, sq2{rect(50, 50, 150, 150)};
  Paths64 frame{rect(0, 0, 100, 100), {Point64(25, 25), Point64(25, 75), Point64(75, 75), Point64(75, 25)}};
  Paths64 touching{rect(100, 0, 200, 100)};
  Paths64 collinear{{Point64(0, 0), Point64(50, 0), Point64(100, 0), Point64(100, 50), Point64(100, 100), Point64(0, 100)}};
  Paths64 bowtie{{Point64(0, 0), Point64(100, 100), Point64(100, 0), Point64(0, 100)}};
  for (int ct = 1; ct <= 4; ++ct)
    for (int fr = 0; fr <= 3; ++fr) {
      emit(sq1, sq2, (ClipType)ct, (FillRule)fr);
      emit(frame, sq2, (ClipType)ct, (FillRule)fr);
      emit(sq1, touching, (ClipType)ct, (FillRule)fr);
      emit(collinear, bowtie, (ClipType)ct, (FillRule)fr);
    }
  // Self-intersecting random polygons (subject only union, and subject vs clip).
  for (int k = 0; k < 40; ++k) {
    Paths64 s{random_poly(6 + (int)rnd(10), 1000)}, c{random_poly(5 + (int)rnd(8), 1000)};
    if (k % 3 == 0) s.push_back(random_poly(4 + (int)rnd(6), 1000));
    emit(s, Paths64{}, ClipType::Union, (FillRule)(k % 4));
    emit(s, c, (ClipType)(1 + k % 4), (FillRule)((k / 4) % 4));
  }
  // Axis-aligned grids (many horizontal edges and joins).
  for (int k = 0; k < 10; ++k) {
    Paths64 s, c;
    for (int i = 0; i < 6; ++i) s.push_back(rect(rnd(20) * 10, rnd(20) * 10, 200 + rnd(10) * 10, 200 + rnd(10) * 10));
    for (int i = 0; i < 4; ++i) c.push_back(rect(rnd(30) * 10, rnd(30) * 10, 100 + rnd(30) * 10, 100 + rnd(30) * 10));
    emit(s, c, (ClipType)(1 + k % 4), FillRule::NonZero);
  }
  std::printf("    println(\"clipper: {} of %d cases differ\", bad);\n    return bad;\n}\n", case_no);
  return 0;
}
